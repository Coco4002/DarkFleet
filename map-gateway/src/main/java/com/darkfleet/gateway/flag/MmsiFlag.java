    /**
     * Resolves the flag state from the 3-digit MID prefix of a 9-digit ship MMSI (starting with digits 2–7).
     * Returns {@code null} for non-ship MMSIs (coast stations, SAR aircraft, aids to navigation) or
     * unassigned MIDs.
     */
    public static Flag resolve(String mmsi) {
        if (mmsi == null || mmsi.length() != 9) {
            return null;
        }
        char first = mmsi.charAt(0);
        if (first < '2' || first > '7') {
            return null;
        }
        for (int i = 0; i < 9; i++) {
            char c = mmsi.charAt(i);
            if (c < '0' || c > '9') {
                return null;
            }
        }
        int mid = (mmsi.charAt(0) - '0') * 100 + (mmsi.charAt(1) - '0') * 10 + (mmsi.charAt(2) - '0');
        return MIDS.get(mid);
    }

